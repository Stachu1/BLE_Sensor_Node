"""Build results/REPORT.md and plots from the pulled results (./sim.sh pull).

Reads results/runs/index.jsonl, results/runs/<hash>/{result.json,S11.csv}, results/opt/*.json and
results/cases/*.json. Plots go to results/plots/.
"""
import glob
import json
import os
import sys

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import antenna as ant  # noqa: E402

RES = os.path.join(HERE, 'results')
PLOTS = os.path.join(RES, 'plots')
BLE = (2.400e9, 2.4835e9)


def load_runs():
	runs = {}
	for p in glob.glob(os.path.join(RES, 'runs', '*', 'result.json')):
		h = os.path.basename(os.path.dirname(p))
		try:
			r = json.load(open(p))
		except Exception:
			continue
		if 'metrics' in r:
			runs[h] = r
	return runs


def s11(h):
	d = np.loadtxt(os.path.join(RES, 'runs', h, 'S11.csv'), delimiter=',', skiprows=1)
	return d[:, 0], d[:, 3], d[:, 4] + 1j * d[:, 5]


def label(r):
	c = r['case']
	a = c['antenna']
	s = 'AE1 as placed (r011)' if a == 'placed' else ant.describe(a)
	extra = []
	if c['board'] == 'r011':
		extra.append('r011 test board')
	if not c.get('battery', True):
		extra.append('no battery')
	if c.get('mask', 'none') != 'none':
		extra.append('mask ' + c['mask'])
	if c.get('er_scale', 1) != 1:
		extra.append('er x%.2f' % c['er_scale'])
	if c.get('mesh'):
		extra.append('mesh ' + ','.join('%s=%g' % kv for kv in c['mesh'].items()))
	if c.get('ports') == 'multi':
		extra.append('4-port')
	return s + (' [' + ', '.join(extra) + ']' if extra else '')


def fmt_bw(bw):
	return '-' if not bw else '%.0f-%.0f (%.0f)' % (bw[0] / 1e6, bw[1] / 1e6, (bw[1] - bw[0]) / 1e6)


def row(h, r):
	m = r['metrics']
	eff = r.get('eff') or []
	e = {round(x['f'] / 1e6): x for x in eff}
	ef = ' / '.join('%.0f' % (100 * e[k]['rad_eff']) for k in sorted(e)) if e else '-'
	tf = ' / '.join('%.0f' % (100 * e[k]['tot_eff']) for k in sorted(e)) if e else '-'
	return '| %s | `%s` | %.3f | %.1f | %.1f | %s | %.1f%+.1fj | %s | %s |' % (
		label(r), h, m['f_min'] / 1e9, m['s_min'], m['ble_worst'], fmt_bw(m['bw10']), m['Z_2440'][0], m['Z_2440'][1], ef, tf)


HEAD = ('| design | run | f(S11 min) GHz | S11 min dB | BLE worst dB | -10 dB band MHz | Z(2.44) ohm | rad. eff % (2.40/2.44/2.48) | total eff % |\n'
	'|---|---|---|---|---|---|---|---|---|')


def plot_s11(hs, runs, name, title):
	fig, ax = plt.subplots(1, 2, figsize=(13, 4.5))
	for h in hs:
		f, dB, Z = s11(h)
		ax[0].plot(f / 1e9, dB, label=label(runs[h])[:70])
		ax[1].plot(f / 1e9, Z.real, label='R ' + h)
		ax[1].plot(f / 1e9, Z.imag, '--', label='X ' + h)
	for a in ax:
		a.axvspan(BLE[0] / 1e9, BLE[1] / 1e9, color='g', alpha=0.1)
		a.grid(alpha=0.3)
		a.set_xlabel('GHz')
	ax[0].axhline(-10, color='k', lw=0.5)
	ax[0].set_ylabel('S11 at J2 (dB)')
	ax[0].set_ylim(-35, 0)
	ax[1].set_ylabel('Zin at J2 (ohm)')
	ax[1].set_ylim(-150, 250)
	ax[0].legend(fontsize=6)
	fig.suptitle(title)
	fig.tight_layout()
	os.makedirs(PLOTS, exist_ok=True)
	fig.savefig(os.path.join(PLOTS, name), dpi=110)
	plt.close(fig)
	return 'plots/' + name


def main():
	runs = load_runs()
	out = ['# C23 rev B antenna simulations (generated by report.py)', '',
		'S11 and Zin at J2 pad 1 (antenna side of the MM8130), L2 = 0R, L3 open, unless noted (b1 runs also had the old antenna-side shunt pads, then called L4, open. That part is gone in rev B and L4 is now the DC-DC inductor). '
		'Efficiency from NF2FF: radiation efficiency = Prad / accepted power, total = Prad / incident power (50 ohm). '
		'BLE band 2400-2483.5 MHz.', '']
	opts = sorted(glob.glob(os.path.join(RES, 'opt', '*.json')))
	for p in opts:
		o = json.load(open(p))
		name = os.path.splitext(os.path.basename(p))[0]
		hist = [h for h in o['history'] if h['hash'] in runs]
		if not hist:
			continue
		hist.sort(key=lambda h: h.get('obj', h.get('s_target', 0)))
		out += ['## Optimizer %s' % name, '', 'Config: `%s`' % json.dumps({k: v for k, v in o['cfg'].items() if k != 'case'}), '',
			'%d runs, %s. Best 5 by objective:' % (len(o['history']), 'finished' if 'best' in o else 'still running'), '',
			HEAD]
		out += [row(h['hash'], runs[h['hash']]) for h in hist[:5]]
		out += ['', '![](%s)' % plot_s11([h['hash'] for h in hist[:3]], runs, 'opt_%s.png' % name, name), '']
	out += ['## All runs', '', HEAD]
	for h, r in sorted(runs.items(), key=lambda kv: label(kv[1])):
		out.append(row(h, r))
	with open(os.path.join(RES, 'REPORT.md'), 'w', encoding='utf-8') as fh:
		fh.write('\n'.join(out) + '\n')
	print('wrote', os.path.join(RES, 'REPORT.md'), len(runs), 'runs')


if __name__ == '__main__':
	main()
